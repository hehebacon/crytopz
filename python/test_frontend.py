
from frontend_api import CrytopzAPI


api = CrytopzAPI(10000.0)


# ============================================================
# MARKET — INITIAL
# ============================================================

api.update_market(
    "BTCUSDT",
    100000,
    100010,
    100005,
    1
)


# ============================================================
# BEFORE
# ============================================================

print("BEFORE:")
print(api.snapshot(["BTCUSDT"]))


# ============================================================
# BUY
# ============================================================

buy_order_id = api.buy(
    "BTCUSDT",
    0.01
)

print("\nBUY ORDER:", buy_order_id)

print("\nAFTER BUY:")
print(api.snapshot(["BTCUSDT"]))


# ============================================================
# MARKET — PRICE GOES UP
# ============================================================

api.update_market(
    "BTCUSDT",
    100090,
    100100,
    100095,
    2
)


print("\nAFTER MARKET UPDATE:")
print(api.snapshot(["BTCUSDT"]))


# ============================================================
# SELL
# ============================================================

sell_order_id = api.sell(
    "BTCUSDT",
    0.01
)

print("\nSELL ORDER:", sell_order_id)


# ============================================================
# AFTER SELL
# ============================================================

print("\nAFTER SELL:")
print(api.snapshot(["BTCUSDT"]))


# ============================================================
# FINAL CHECK
# ============================================================

print("\nFINAL POSITION:")
print(api.positions())

print("\nFINAL REALIZED PNL:")
print(api.realized_pnl())


# ============================================================
# CLOSE
# ============================================================

api.close()

